#!/usr/bin/env node
/**
 * 将主世界角色精灵登记进 assets/manifest.json。
 *
 * 用法：
 *   node tools/register-world-character-sprites.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';

const MANIFEST = resolve('assets/manifest.json');
const GENERATED_AT = process.env.GENERATED_AT ?? new Date().toISOString();

const WORLD_CHARACTERS = {
  'map-sprite.player-v1': 'cultivator protagonist, frail mortal body-cultivator in patched hemp robe',
  'map-sprite.herb-gatherer-v1': 'village herb gatherer with woven herb basket',
  'map-sprite.array-smith-lu-v1': 'old array-smith Lu with bronze compass and work apron',
  'map-sprite.liaochen-v1': 'wandering monk-like cultivator Liaochen with staff and travel pack',
  'map-sprite.wangyan-elder-v1': 'elder Wangyan with bamboo slip and weathered scholar robe',
  'map-sprite.xiao-wuji-v1': 'Xiao Wuji, elegant rival cultivator in restrained pale robes',
  'map-sprite.market-merchant-v1': 'valley market merchant with abacus and coin pouch',
  'map-sprite.tea-shed-elder-v1': 'roadside tea-shed elder with clay teapot',
  'map-sprite.processing-artisan-v1': 'herb processing artisan with dried herb bundle and brown apron',
  'map-sprite.patrol-guard-v1': 'valley patrol guard with bamboo spear and talisman pennant'
};

const manifest = JSON.parse(readFileSync(MANIFEST, 'utf-8'));
const byId = new Map(manifest.sprites.map((entry, index) => [entry.id, { entry, index }]));

for (const [id, role] of Object.entries(WORLD_CHARACTERS)) {
  const path = `map-sprites/${id}.png`;
  const file = resolve('assets', path);
  const buffer = readFileSync(file);
  const checksum = createHash('sha256').update(buffer).digest('hex');
  const entry = {
    id,
    path,
    type: 'png',
    checksum,
    license: 'AI-Generated',
    source: `gpt-image-2 via relay; C3 HD-2D ink-wash xianxia world character sprite; role=${role}; generated by tools/gen-world-character-sprites.mjs and postprocessed by tools/postprocess-world-character-art.py; no API key stored`,
    human_edits: [
      'Background cleanup, character crop, 96x96 transparent canvas, limited-color pixel-art pass, and map-scale alignment.'
    ],
    ai_disclosed: true,
    src: {
      model: process.env.CG_MODEL ?? 'gpt-image-2',
      endpoint: (process.env.CG_API_BASE ?? 'https://fast.qianxing.us.ci').replace(/\/+$/, ''),
      prompt: `C3 HD-2D ink-wash xianxia world character sprite; ${role}; full-body 3/4 top-down RPG stance; transparent background; no scenery; generated_at=${GENERATED_AT}`,
      seed: null,
      master_ref: ['assets/references/art-bible-cultivation-courtyard-v1.png', 'assets/maps/map.farmstead-courtyard-v1.png'],
      ref_imgs: [],
      generated_at: GENERATED_AT
    }
  };

  const existing = byId.get(id);
  if (existing) {
    manifest.sprites[existing.index] = entry;
  } else {
    manifest.sprites.push(entry);
  }
}

writeFileSync(MANIFEST, `${JSON.stringify(manifest, null, 1)}\n`);
console.log(JSON.stringify({ updated: Object.keys(WORLD_CHARACTERS).length, manifest: MANIFEST }, null, 2));
