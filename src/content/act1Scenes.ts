export interface Act1Choice {
  /** 选项按钮文案。 */
  readonly label: string;
  /** 选中后立刻浮现的一句。 */
  readonly response: string;
  /** 选中后可切换的 CG。 */
  readonly cg?: string;
  /** 选中后可切换的 manifest CG AssetId。 */
  readonly cgAssetId?: string;
}

export type Act1SceneId = 'duel' | 'ash' | 'relic' | 'ring' | 'scroll';

export interface Act1Scene {
  readonly id: Act1SceneId;
  /** 可选 CG 资源路径；缺失或加载失败时退化为 CSS 水墨氛围。当前第一幕不挂 CG。 */
  readonly cg?: string;
  /** 可选 manifest CG AssetId；优先于 cg 路径。 */
  readonly cgAssetId?: string;
  /** 按顺序浮现的旁白/对白行。 */
  readonly lines: readonly string[];
  /** 末尾可出现的选项；可选。 */
  readonly choices?: readonly Act1Choice[];
  /** 任一选项后浮现的收敛行；可选。 */
  readonly converge?: string;
}

